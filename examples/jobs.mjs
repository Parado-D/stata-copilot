#!/usr/bin/env node
/**
 * Background jobs, from the client's side.
 *
 *   node examples/jobs.mjs
 *
 * The point of the demo is the *concurrency*, not the arithmetic: a job runs in
 * its own Stata process, so the interactive session keeps answering while the
 * job is still working. That is what makes an hour-long imputation possible —
 * the HTTP service alone refuses a second call while one is running.
 *
 * The generated do-file takes ~12 s: it prints progress, writes a small file,
 * and ends. The demo then shows status, log, and kill on a second job.
 */

import { mkdirSync, writeFileSync, readdirSync } from 'node:fs';
import path from 'node:path';

import { REPO_ROOT, startServer } from './mcp-client.mjs';

const OUT = path.join(REPO_ROOT, 'examples', 'jobs-output');
mkdirSync(OUT, { recursive: true });

const client = startServer({
  command: process.execPath,
  args: [path.join(REPO_ROOT, 'bin', 'stata-copilot.mjs'), '--root', REPO_ROOT],
});

const log = (...parts) => console.log(...parts);
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

function payload(result) {
  const block = result.content?.find((entry) => entry.type === 'text');
  if (!block) throw new Error('the tool returned no text block');
  return JSON.parse(block.text);
}

function requireOk(result, what) {
  const body = payload(result);
  if (result.isError) throw new Error(`${what} failed: ${JSON.stringify(body.error ?? body)}`);
  return body;
}

const SLOW = `// Generated by examples/jobs.mjs — a job slow enough to watch.
display "job start: " c(current_time)
sysuse auto, clear
gen double sq = .
forvalues i = 1/20 {
    quietly replace sq = sqrt(price) if _n == \`i'
    display "step \`i' of 20"
    sleep 500
}
count if !missing(sq)
display "job end: " c(current_time)
`;

try {
  const init = await client.initialize();
  log(`server ${init.serverInfo?.name} ${init.serverInfo?.version}`);

  const doPath = path.join(OUT, 'slow-job.do');
  writeFileSync(doPath, SLOW, 'utf8');

  log('\n1. submit — returns at once, with a job id');
  const job = requireOk(
    await client.callTool('stata_job_submit', { file: doPath, cwd: OUT, label: 'demo loop' }),
    'stata_job_submit',
  );
  log(`   ${job.jobId} · ${job.state} · pid ${job.pid} · ceiling ${job.timeoutSeconds}s`);

  log('\n2. the interactive session is still free while the job runs');
  const t0 = Date.now();
  const interactive = requireOk(
    await client.callTool('stata_run', { code: 'display 1 + 1', cwd: OUT }),
    'stata_run',
  );
  log(`   stata_run returned in ${Date.now() - t0} ms · output: ${interactive.output.trim()}`);

  log('\n3. poll — the job keeps working while the session stays usable');
  await sleep(2500);
  const mid = requireOk(
    await client.callTool('stata_job_status', { jobId: job.jobId, cwd: OUT }),
    'stata_job_status',
  );
  const tailLine = (mid.outputTail ?? '').trim().split('\n').filter(Boolean).slice(-1)[0] ?? '(no log yet)';
  log(`   ${mid.state} · ${(mid.durationMs / 1000).toFixed(1)}s elapsed · tail: ${tailLine.trim()}`);

  log('\n4. log — read progress while it runs');
  const progress = requireOk(
    await client.callTool('stata_job_log', { jobId: job.jobId, cwd: OUT, tail: 400 }),
    'stata_job_log',
  );
  const lastLines = progress.text.trim().split('\n').slice(-3);
  for (const line of lastLines) log(`   ${line}`);

  log('\n5. wait for the end, then read the verdict');
  let final = mid;
  for (let i = 0; i < 120 && final.state === 'running'; i++) {
    await sleep(500);
    final = requireOk(await client.callTool('stata_job_status', { jobId: job.jobId, cwd: OUT }), 'stata_job_status');
  }
  log(`   ${final.state} · ${(final.durationMs / 1000).toFixed(1)}s · returnCode ${final.returnCode}`);

  log('\n6. a job that will not finish is stopped, and its log is kept');
  const longPath = path.join(OUT, 'long-job.do');
  writeFileSync(longPath, 'display "starting"\nsleep 60000\ndisplay "never"\n', 'utf8');
  const longJob = requireOk(
    await client.callTool('stata_job_submit', { file: longPath, cwd: OUT, label: 'to be killed', timeout: 600 }),
    'stata_job_submit',
  );
  await sleep(1500);
  const killed = requireOk(
    await client.callTool('stata_job_kill', { jobId: longJob.jobId, cwd: OUT }),
    'stata_job_kill',
  );
  log(`   ${killed.jobId} · ${killed.state} after ${(killed.durationMs / 1000).toFixed(1)}s · log: ${path.basename(killed.log)}`);

  log('\n7. list — records persist under <cwd>/.stata-copilot/jobs/');
  const listing = requireOk(await client.callTool('stata_job_list', { cwd: OUT }), 'stata_job_list');
  log(`   ${listing.count} job(s): ${listing.jobs.map((entry) => `${entry.jobId}=${entry.state}`).join(', ')}`);
  log(`   files on disk: ${readdirSync(path.join(OUT, '.stata-copilot', 'jobs')).length}`);
} catch (err) {
  console.error(`\ndemo failed: ${err.message}`);
  process.exitCode = 1;
} finally {
  client.close();
}
